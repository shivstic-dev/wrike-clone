echo "     → Create job: GET https://<api>.onrender.com/api/v1/health"
echo "     → Every 10 minutes during work hours"
echo "     → This prevents Render's free tier from sleeping"
echo ""
echo "  □ First login:"
echo "     → Go to https://<app>.vercel.app"
