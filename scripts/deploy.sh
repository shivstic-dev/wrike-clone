echo "  □ Security:"
echo "     → Rotate the seeded admin password immediately"
echo "     → Keep JWT_SECRET, SETUP_KEY, and DB password safe"
echo "     → Verify the admin slug field is hidden (DEFAULT_TENANT_SLUG works)"
echo ""

